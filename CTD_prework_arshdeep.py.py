# Script tells gardner whether to water their plant today
# Ask what type of plant and number of days last watered
# Notes to water every 3 days
plant = input("What kind of plant do you have? ")
days = input("How many days since you last watered it? ")

if not days.isdigit():
  print(days + " is an invalid entry broski :)")
else:
  days = int(days)
  if days >= 3:
    print("Your " + plant + " has gone " + str(days) + " days without water")
  elif days == 0:
    print("Already watered " + plant + ", check again in 3 days")
  else:
    print("Your " + plant + " was watered " + str(days) + " day(s) ago")
# Example run 1
# Inputs: tomato, 5
# Output: Your tomato has gone 5 days without water

# Example run 2
# Inputs: basil, 1
# Output: Your basil was watered 1 day(s) ago